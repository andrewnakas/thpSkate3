#!/usr/bin/env python3
"""Declare the libultra functions N64Recomp hands to the runtime (<name>_recomp), so the generated C compiles.
Same idea as the PW64 port's tool: the names come from N64Recomp's own symbol_lists.cpp (three lists).

  python tools/gen_reimplemented_decls.py  -> recomp/include/reimplemented_decls.h
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N64MR = os.environ.get('N64MR', os.path.join(ROOT, 'deps/pw64/lib/N64ModernRuntime'))

text = open(os.path.join(N64MR, 'N64Recomp', 'src', 'symbol_lists.cpp'), errors='replace').read()
names = set()
for lst in ('reimplemented_funcs', 'ignored_funcs', 'renamed_funcs'):
    m = re.search(lst + r'\s*\{(.*?)\n\};', text, re.S)
    if not m:
        sys.exit(f'could not find {lst}')
    names.update(re.findall(r'"([A-Za-z_]\w*)"', m.group(1)))
out = ['/* generated by tools/gen_reimplemented_decls.py: do not edit */', '#ifndef REIMPLEMENTED_DECLS_H',
       '#define REIMPLEMENTED_DECLS_H', '#include "recomp.h"', '#ifdef __cplusplus', 'extern "C" {', '#endif']
out += [f'void {n}_recomp(uint8_t* rdram, recomp_context* ctx);' for n in sorted(names)]
cfg = open(os.path.join(ROOT, 'recomp', 'thps.toml')).read()
m = re.search(r'^ignored\s*=\s*\[(.*?)\]', cfg, re.S | re.M)
ours = sorted(set(re.findall(r'"([A-Za-z_]\w*)"', m.group(1)))) if m else []
out += ['/* functions recomp/thps.toml marks ignored: the port defines them */']
out += [f'void {n}(uint8_t* rdram, recomp_context* ctx);' for n in ours]
out += ['#ifdef __cplusplus', '}', '#endif', '#endif', '']
open(os.path.join(ROOT, 'recomp', 'include', 'reimplemented_decls.h'), 'w').write('\n'.join(out))
print(f'{len(names)} declarations -> recomp/include/reimplemented_decls.h')
